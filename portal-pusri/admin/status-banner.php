<?php

/*
|--------------------------------------------------------------------------
| PROTEKSI ADMIN KEYCLOAK
|--------------------------------------------------------------------------
*/

require_once __DIR__ . "/../includes/auth.php";

requireRole("ADMIN");


/*
|--------------------------------------------------------------------------
| CSRF PROTECTION
|--------------------------------------------------------------------------
*/

require_once __DIR__ . "/../includes/csrf.php";


/*
|--------------------------------------------------------------------------
| DATABASE
|--------------------------------------------------------------------------
*/

require_once __DIR__ . "/../config/database.php";


/*
|--------------------------------------------------------------------------
| HANYA IZINKAN METHOD POST
|--------------------------------------------------------------------------
*/

if (
    $_SERVER["REQUEST_METHOD"]
    !== "POST"
) {

    header(
        "Allow: POST"
    );


    http_response_code(
        405
    );


    die(
        "405 - Method Not Allowed"
    );
}


/*
|--------------------------------------------------------------------------
| VALIDASI CSRF
|--------------------------------------------------------------------------
*/

requireCsrf();


/*
|--------------------------------------------------------------------------
| VALIDASI ID
|--------------------------------------------------------------------------
*/

$idInput =
    $_POST["id"]
    ?? null;


if (
    $idInput === null
    ||
    filter_var(
        $idInput,
        FILTER_VALIDATE_INT
    ) === false
) {

    header(
        "Location: /portal-pusri/admin/banner.php",
        true,
        302
    );

    exit;
}


$id =
    (int)
    $idInput;


if (
    $id <= 0
) {

    header(
        "Location: /portal-pusri/admin/banner.php",
        true,
        302
    );

    exit;
}


/*
|--------------------------------------------------------------------------
| TOGGLE STATUS BANNER
|--------------------------------------------------------------------------
|
| Status langsung dibalik di database:
|
| Aktif     1 → 0
| Nonaktif  0 → 1
|
| Tidak perlu SELECT status terlebih dahulu.
|--------------------------------------------------------------------------
*/

try {

    /*
    |--------------------------------------------------------------------------
    | PREPARED STATEMENT
    |--------------------------------------------------------------------------
    */

    $stmt =
        $conn->prepare(
            "
            UPDATE banners

            SET is_active =
                CASE
                    WHEN is_active = 1
                    THEN 0
                    ELSE 1
                END

            WHERE id = ?
            "
        );


    /*
    |--------------------------------------------------------------------------
    | BIND PARAMETER
    |--------------------------------------------------------------------------
    */

    $stmt->bind_param(
        "i",
        $id
    );


    /*
    |--------------------------------------------------------------------------
    | EXECUTE
    |--------------------------------------------------------------------------
    */

    $stmt->execute();


    /*
    |--------------------------------------------------------------------------
    | CEK RECORD YANG BERUBAH
    |--------------------------------------------------------------------------
    */

    $affectedRows =
        $stmt->affected_rows;


    $stmt->close();


    /*
    |--------------------------------------------------------------------------
    | BANNER TIDAK DITEMUKAN
    |--------------------------------------------------------------------------
    */

    if (
        $affectedRows !== 1
    ) {

        header(
            "Location: /portal-pusri/admin/banner.php",
            true,
            302
        );

        exit;
    }


} catch (Throwable $e) {

    /*
    |--------------------------------------------------------------------------
    | SIMPAN DETAIL ERROR KE LOG
    |--------------------------------------------------------------------------
    |
    | Jangan tampilkan detail MySQL ke browser.
    |--------------------------------------------------------------------------
    */

    error_log(
        "Portal Layanan SDM PUSRI Banner Status Error ID "
        . $id
        . ": "
        . get_class($e)
        . ": "
        . $e->getMessage()
    );


    http_response_code(
        500
    );


    die(
        "Status banner gagal diubah. Silakan coba kembali."
    );
}


/*
|--------------------------------------------------------------------------
| BERHASIL
|--------------------------------------------------------------------------
*/

header(
    "Location: /portal-pusri/admin/banner.php?success=status",
    true,
    302
);

exit;